"""Install public sibling dependencies from source before package-index releases exist."""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import tomllib
from pathlib import Path


def run(*args: str) -> None:
    subprocess.run(args, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python", default="3.12")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    doc = json.loads((root / ".frontier-dependencies.json").read_text())
    siblings = root / ".frontier-deps"
    checkouts = [root]
    for name in doc["repositories"]:
        if not re.fullmatch(r"[a-z0-9-]+", name):
            raise ValueError(f"invalid sibling repository {name!r}")
        path = siblings / name
        if not path.exists():
            path.parent.mkdir(parents=True, exist_ok=True)
            run(
                "git",
                "clone",
                "--depth=1",
                f"https://github.com/DimensionLab/{name}.git",
                str(path),
            )
        checkouts.append(path)
    patches: dict[str, str] = {}
    packages: list[Path] = []
    for checkout in checkouts:
        for manifest in checkout.glob("crates/*/Cargo.toml"):
            name = tomllib.loads(manifest.read_text())["package"]["name"]
            patches[name] = str(manifest.parent.resolve())
        for manifest in checkout.glob("packages/**/pyproject.toml"):
            if "project" in tomllib.loads(manifest.read_text()):
                packages.append(manifest.parent)
        native = checkout / "crates/frontier-py"
        if (native / "pyproject.toml").exists():
            packages.append(native)
    config = root / ".cargo/config.toml"
    lines = ["# Generated by tools/bootstrap.py", "[patch.crates-io]"]
    lines += [f"{name} = {{ path = {json.dumps(path)} }}" for name, path in sorted(patches.items())]
    if packages:
        run("uv", "venv", "--allow-existing", "--python", args.python, str(root / ".venv"))
        import os

        python = root / ".venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        lines += ["", "[env]", f"PYO3_PYTHON = {json.dumps(str(python))}"]
    config.parent.mkdir(exist_ok=True)
    config.write_text("\n".join(lines) + "\n")
    if packages:
        install = ["uv", "pip", "install", "--no-sources", "--python", str(python)]
        for package in packages:
            project = tomllib.loads((package / "pyproject.toml").read_text())["project"]
            extra = "[test]" if "test" in project.get("optional-dependencies", {}) else ""
            install += ["-e", str(package) + extra]
        install += ["pytest>=8.3", "pytest-cov>=6", "ruff>=0.13", "pyright>=1.1.400"]
        run(*install)
    print("Public source dependencies ready. See CONTRIBUTING.md for checks.")


if __name__ == "__main__":
    main()
