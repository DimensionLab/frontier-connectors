"""Generate everything that is derived from the ``plugin.toml`` manifests.

The ``plugin.toml`` in each plugin's import package is the single source of truth of a
plugin. From it this script writes

* the plugin's ``pyproject.toml`` (name, version, dependencies, entry points) and Nx project,
* its ``README.md`` when the plugin has none,
* the ``frontier-connectors-all`` and ``frontier-connectors-oss`` meta-distributions,
* ``src/frontier_connectors/plugins/catalog.json`` of the framework (what ``plugins search``
  and ``plugins install <id>`` know about without anything being installed),
* ``src/frontier_connectors/plugins/marketplace.json``: everything the application's
  Connectors page shows (name, description, author, tags, category, formats, credentials,
  README text) plus the connector rows of the registry, so the control plane can list and
  describe plugins without starting Python.

    uv run python packages/frontier-connectors/tools/sync_plugins.py           # write
    uv run python packages/frontier-connectors/tools/sync_plugins.py --check   # CI: fail on drift

Only the TOML files and READMEs are read, with one exception: the connector rows of
``marketplace.json`` (extensions, sample kinds, steady / transient) are attributes of the
connector classes, so that file asks the registry for them in a subprocess with an empty
``FRONTIER_HOME``. When the plugins cannot be imported the rows of the existing file are kept.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PLUGINS = ROOT.parent / "connectors"
CATALOG = ROOT / "src" / "frontier_connectors" / "plugins" / "catalog.json"
MARKETPLACE = ROOT / "src" / "frontier_connectors" / "plugins" / "marketplace.json"
OFFICIAL_COMPANY = "DimensionLab s.r.o."
#: keys of a registry row that depend on the machine it was generated on
_LOCAL_ROW_KEYS = ("missing", "status", "source", "credentials_present")
FRAMEWORK = "frontier-connectors"
FRAMEWORK_REQ = "frontier-connectors>=0.9.0,<0.10"
PYTHON_REQ = ">=3.11,<3.14"
BUILD = 'requires = ["uv_build>=0.8.9,<0.9.0"]\nbuild-backend = "uv_build"'
PREFIX = {"connector": "frontier-connector-", "importer": "frontier-importer-"}
PUBLIC_PLUGINS = frozenset(
    {
        "arrays",
        "catalyst",
        "cgns",
        "code-saturne",
        "ensight",
        "exporter-catalyst",
        "geometry",
        "meshio",
        "nek5000",
        "openfoam",
        "palabos",
        "pyfr",
        "tabular",
        "vtk",
    }
)
HEADER = (
    "# Generated by tools/sync_plugins.py from src/{module}/plugin.toml. Do not edit by hand:\n"
    "# change the manifest and run `uv run python packages/frontier-connectors/tools/"
    "sync_plugins.py`.\n"
)


def dist_name(manifest: dict[str, Any]) -> str:
    pid = manifest["id"]
    if manifest["kind"] == "exporter":
        return "frontier-" + pid if pid.startswith("exporter-") else "frontier-exporter-" + pid
    return PREFIX[manifest["kind"]] + pid


def load_manifests() -> list[tuple[Path, str, dict[str, Any]]]:
    """(plugin directory, import package, manifest) for every plugin, sorted by id."""
    sys.path.insert(0, str(ROOT / "src"))
    from frontier_connectors.plugins.manifest import ManifestError, validate

    found = []
    errors = []
    for toml in sorted(PLUGINS.glob("*/src/*/plugin.toml")):
        doc = tomllib.loads(toml.read_text(encoding="utf-8"))
        try:
            validate(doc, source=str(toml.relative_to(PLUGINS)))
        except ManifestError as e:
            errors.append(str(e))
            continue
        found.append((toml.parents[2], toml.parent.name, doc))
    if errors:
        raise SystemExit("invalid manifests:\n  " + "\n  ".join(errors))
    ids = [m["id"] for _, _, m in found]
    dup = sorted({i for i in ids if ids.count(i) > 1})
    if dup:
        raise SystemExit(f"duplicate plugin ids: {dup}")
    return sorted(found, key=lambda t: t[2]["id"])


def _toml_str(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _table(title: str, entries: dict[str, str]) -> str:
    if not entries:
        return ""
    body = "\n".join(f"{k} = {_toml_str(v)}" for k, v in sorted(entries.items()))
    return f"\n[{title}]\n{body}\n"


def pyproject(module: str, m: dict[str, Any], dists: dict[str, str]) -> str:
    name = dist_name(m)
    unknown = [p for p in m.get("plugins", []) if p not in dists]
    if unknown:
        raise SystemExit(f"{m['id']}: plugins {unknown} are not first-party plugin ids")
    plugin_deps = [dists[p] for p in m.get("plugins", [])]
    deps = [FRAMEWORK_REQ, *m.get("requires", []), *[f"{d}>={m['version']}" for d in plugin_deps]]
    description = m.get("summary") or m["name"]
    extras: dict[str, list[str]] = {}
    for opt in m.get("optional", []):
        if opt.get("extra"):
            extras.setdefault(opt["extra"], []).append(opt.get("requirement", opt["package"]))
    out = HEADER.format(module=module)
    out += "[project]\n"
    out += f"name = {_toml_str(name)}\n"
    out += f"version = {_toml_str(m['version'])}\n"
    out += f"description = {_toml_str('DimensionLab Frontier plugin: ' + description)}\n"
    out += 'readme = "README.md"\n'
    out += f"requires-python = {_toml_str(PYTHON_REQ)}\n"
    out += f"license = {_toml_str(m.get('licence', 'Apache-2.0'))}\n"
    if m["id"] not in PUBLIC_PLUGINS:
        out += 'classifiers = ["Private :: Do Not Upload"]\n'
    out += "dependencies = [\n" + "".join(f"  {_toml_str(d)},\n" for d in deps) + "]\n"
    if extras:
        out += "\n[project.optional-dependencies]\n"
        for extra, reqs in sorted(extras.items()):
            out += f"{extra} = [" + ", ".join(_toml_str(r) for r in reqs) + "]\n"
    out += _table('project.entry-points."frontier.plugins"', {m["id"]: module})
    out += _table('project.entry-points."frontier.connectors"', m.get("connectors", {}))
    out += _table('project.entry-points."frontier.importers"', m.get("importers", {}))
    if m.get("exporter"):
        out += _table(
            'project.entry-points."frontier.exporters"', {m["exporter"]["vendor"]: module}
        )
    out += f"\n[build-system]\n{BUILD}\n"
    sources = {FRAMEWORK: "{ workspace = true }"} | {d: "{ workspace = true }" for d in plugin_deps}
    out += "\n[tool.uv.sources]\n" + "".join(f"{k} = {v}\n" for k, v in sorted(sources.items()))
    return out


def readme(m: dict[str, Any], module: str) -> str:
    lines = [
        f"# {dist_name(m)}",
        "",
        m.get("description") or m.get("summary") or m["name"],
        "",
        "## Install",
        "",
        "```bash",
        f"python -m frontier_connectors plugins install {m['id']}",
        f"python -m frontier_connectors plugins info {m['id']}",
        "```",
        "",
        "## Requirements and licence",
        "",
        f"Licence: {m.get('licence', '')}.",
        "",
    ]
    return "\n".join(lines)


def all_pyproject(dists: list[str], version: str, *, public: bool = False) -> str:
    name = "frontier-connectors-oss" if public else "frontier-connectors-all"
    description = "open-tool and neutral-format" if public else "connector, exporter and importer"
    out = (
        "# Generated by tools/sync_plugins.py. Do not edit by hand.\n"
        "[project]\n"
        f'name = "{name}"\n'
        f"version = {_toml_str(version)}\n"
        'description = "DimensionLab Frontier: the connector framework with every first-party '
        f'{description} plugin"\n'
        'readme = "README.md"\n'
        f"requires-python = {_toml_str(PYTHON_REQ)}\n"
        'license = "Apache-2.0"\n'
        + ("" if public else 'classifiers = ["Private :: Do Not Upload"]\n')
        + "dependencies = [\n"
        f"  {_toml_str(FRAMEWORK_REQ)},\n"
    )
    out += "".join(f"  {_toml_str(d + '>=' + version)},\n" for d in dists)
    out += f"]\n\n[build-system]\n{BUILD}\n\n[tool.uv.sources]\n"
    out += "".join(f"{d} = {{ workspace = true }}\n" for d in sorted([FRAMEWORK, *dists]))
    return out


def nx_project(directory: Path, name: str, *, public: bool, dependencies: list[str]) -> str:
    project_name = (
        name + "-py" if name in {"frontier-connector-openfoam", "frontier-connector-vtk"} else name
    )
    relative = directory.relative_to(ROOT.parents[1]).as_posix()
    targets: dict[str, Any] = {}
    commands = {
        "build": f"uv build --package {name} --out-dir {relative}/dist",
        "lint": f"uv run --no-sync ruff check {relative}",
        "typecheck": f"uv run --no-sync pyright {relative}",
        "test": f"uv run --no-sync pytest {relative}/tests -o addopts= --import-mode=importlib -q",
    }
    for target, command in commands.items():
        targets[target] = {
            "executor": "nx:run-commands",
            "cache": True,
            "inputs": ["python", "^python"],
            "outputs": ["{projectRoot}/dist"] if target == "build" else [],
            "options": {"command": command},
        }
    # Wheels contain requirements, not bundled copies of sibling packages.
    targets["build"]["dependsOn"] = []
    return (
        json.dumps(
            {
                "$schema": "../../../node_modules/nx/schemas/project-schema.json",
                "name": project_name,
                "projectType": "library",
                "root": relative,
                "sourceRoot": f"{relative}/src",
                "targets": targets,
                "implicitDependencies": ["frontier-connectors-py", *dependencies],
                "tags": [
                    "lang:python",
                    "scope:connectors",
                    "kind:plugin",
                    "visibility:public" if public else "visibility:private",
                ],
            },
            indent=2,
        )
        + "\n"
    )


def catalog(manifests: list[tuple[Path, str, dict[str, Any]]]) -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from frontier_connectors.plugins.installer import catalog_entry

    rows = [catalog_entry(m, dist_name(m)) for _, _, m in manifests]
    doc = {
        "schema": "frontier-plugin-catalog/1",
        "generated_by": "tools/sync_plugins.py",
        "plugins": rows,
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def _registry_rows(command: str) -> list[dict[str, Any]] | None:
    """Rows of ``python -m frontier_connectors <command> --json`` with every plugin enabled
    (an empty ``FRONTIER_HOME``), or ``None`` when the registry cannot be asked."""
    with tempfile.TemporaryDirectory() as home:
        env = os.environ | {"FRONTIER_HOME": home, "PYTHONPATH": str(ROOT / "src")}
        proc = subprocess.run(  # noqa: S603 - fixed arguments, this interpreter
            [sys.executable, "-m", "frontier_connectors", command, "--json", "--compact"],
            capture_output=True,
            text=True,
            check=False,
            env=env,
        )
    try:
        rows = json.loads(proc.stdout)
    except ValueError:
        return None
    if proc.returncode != 0 or not isinstance(rows, list):
        return None
    for row in rows:
        for key in _LOCAL_ROW_KEYS:
            row.pop(key, None)
    return sorted(rows, key=lambda r: r["id"])


def _union(rows: list[dict[str, Any]], key: str) -> list[str]:
    out: list[str] = []
    for row in rows:
        out += [v for v in row.get(key, []) if v not in out]
    return out


def last_changed(directory: Path) -> str:
    """The date (``YYYY-MM-DD``, committer time) of the last commit that touched a plugin's
    folder: what "recently updated" means in the marketplace. Empty outside a git checkout
    (an sdist) or for a folder that was never committed; the caller then keeps the date
    already in the catalog, and only after that the manifest's own ``updated``."""
    try:
        out = subprocess.run(  # noqa: S603
            ["git", "log", "-1", "--format=%cs", "--", str(directory)],  # noqa: S607
            cwd=directory,
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return ""
    date = out.stdout.strip()
    return date if out.returncode == 0 and len(date) == 10 else ""


def _without_dates(text: str) -> str:
    """A marketplace document with the ``updated`` dates blanked: they follow from the
    commit history, so a commit that touches a plugin moves its date without making the
    committed catalog "stale" for ``--check``."""
    try:
        doc = json.loads(text)
    except ValueError:
        return text
    for plugin in doc.get("plugins", []):
        plugin["updated"] = ""
    return json.dumps(doc, indent=1, ensure_ascii=False)


def marketplace(manifests: list[tuple[Path, str, dict[str, Any]]]) -> str:
    """The marketplace catalog: one entry per plugin with its manifest fields and README, and
    the registry's connector and importer rows."""
    sys.path.insert(0, str(ROOT / "src"))
    from frontier_connectors.plugins.manifest import DATA_MODEL_VERSION, auth_providers

    previous: dict[str, Any] = {}
    if MARKETPLACE.is_file():
        previous = json.loads(MARKETPLACE.read_text(encoding="utf-8"))
    connectors = _registry_rows("list")
    importers = _registry_rows("importers")
    known = {c for _, _, m in manifests for c in m.get("connectors", {})}
    if connectors is None or {r["id"] for r in connectors} != known:
        # a plugin does not import here: keep what was generated where it did
        connectors = previous.get("connectors", [])
    if importers is None:
        importers = previous.get("importers", [])
    previous_dates = {p["id"]: p.get("updated", "") for p in previous.get("plugins", [])}
    plugins = []
    for directory, module, m in manifests:
        own = [r for r in connectors if r.get("plugin") == m["id"]]
        exporter = dict(m.get("exporter") or {})
        if exporter:
            files = directory / "src" / module / exporter.get("files", "files")
            exporter["files"] = sorted(
                str(f.relative_to(files)) for f in files.rglob("*") if f.is_file()
            )
        author = dict(m.get("author", {}))

        def read(name: str, directory: Path = directory) -> str:
            path = directory / name
            return path.read_text(encoding="utf-8") if path.is_file() else ""

        plugins.append(
            {
                "id": m["id"],
                "kind": m["kind"],
                "dist": dist_name(m),
                "module": module,
                "folder": directory.name,
                "name": m["name"],
                "description": m.get("description") or m.get("summary", ""),
                "summary": m.get("summary", ""),
                "version": m["version"],
                "data_model_version": m["data_model_version"],
                "author": author,
                "official": author.get("company", "") == OFFICIAL_COMPANY,
                "category": m.get("category") or "other",
                "tags": list(m.get("tags", [])),
                "keywords": list(m.get("keywords", [])),
                "icon": m.get("icon", ""),
                "homepage": m.get("homepage", ""),
                # optional: no key when the manifest names no repository
                **({"repository": m["repository"]} if m.get("repository") else {}),
                "license": m.get("licence", m.get("license", "")),
                "updated": last_changed(directory)
                or previous_dates.get(m["id"], "")
                or m.get("updated", ""),
                "vendor": m.get("vendor", ""),
                "maturity": m.get("maturity", ""),
                "formats": _union(own, "formats") or list(m.get("formats", [])),
                "extensions": _union(own, "extensions"),
                "kinds": _union(own, "kinds"),
                "temporal": _union(own, "temporal"),
                "requires": list(m.get("requires", [])),
                "plugins": list(m.get("plugins", [])),
                "suggests": list(m.get("suggests", [])),
                "optional": [dict(o) for o in m.get("optional", [])],
                "connectors": sorted(m.get("connectors", {})),
                "importers": sorted(m.get("importers", {})),
                "exporter": exporter or None,
                "auth": auth_providers(m.get("auth", [])),
                "readme": read(m.get("readme", "README.md")),
                "changelog": read("CHANGELOG.md"),
            }
        )
    doc = {
        "schema": "frontier-plugin-marketplace/1",
        "generated_by": "tools/sync_plugins.py",
        "data_model_version": DATA_MODEL_VERSION,
        "plugins": plugins,
        "connectors": connectors,
        "importers": importers,
    }
    return json.dumps(doc, indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Generate the files derived from plugin.toml.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = ap.parse_args()
    manifests = load_manifests()
    dists = {m["id"]: dist_name(m) for _, _, m in manifests}
    version = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    outputs: dict[Path, str] = {}
    for directory, module, m in manifests:
        if m["version"] != version:
            raise SystemExit(
                f"{m['id']}: version {m['version']} differs from the framework {version}"
            )
        outputs[directory / "pyproject.toml"] = pyproject(module, m, dists)
        dependencies = [
            dists[pid] + ("-py" if pid in {"openfoam", "vtk"} else "")
            for pid in m.get("plugins", [])
        ]
        outputs[directory / "project.json"] = nx_project(
            directory,
            dist_name(m),
            public=m["id"] in PUBLIC_PLUGINS,
            dependencies=dependencies,
        )
        if not (directory / "README.md").is_file():
            outputs[directory / "README.md"] = readme(m, module)
    outputs[PLUGINS / "all" / "pyproject.toml"] = all_pyproject(sorted(dists.values()), version)
    outputs[PLUGINS / "all" / "project.json"] = nx_project(
        PLUGINS / "all",
        "frontier-connectors-all",
        public=False,
        dependencies=[
            d + ("-py" if pid in {"openfoam", "vtk"} else "") for pid, d in sorted(dists.items())
        ],
    )
    outputs[PLUGINS / "oss" / "pyproject.toml"] = all_pyproject(
        sorted(d for pid, d in dists.items() if pid in PUBLIC_PLUGINS),
        version,
        public=True,
    )
    outputs[PLUGINS / "oss" / "project.json"] = nx_project(
        PLUGINS / "oss",
        "frontier-connectors-oss",
        public=True,
        dependencies=[
            d + ("-py" if pid in {"openfoam", "vtk"} else "")
            for pid, d in sorted(dists.items())
            if pid in PUBLIC_PLUGINS
        ],
    )
    outputs[CATALOG] = catalog(manifests)
    outputs[MARKETPLACE] = marketplace(manifests)
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.check and path == MARKETPLACE and current is not None:
            if _without_dates(current) == _without_dates(text):
                continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    rel = [str(p.relative_to(ROOT.parent)) for p in stale]
    if args.check and stale:
        print("stale generated files (run tools/sync_plugins.py):\n  " + "\n  ".join(rel))
        return 1
    print(f"{len(manifests)} plugins; " + (f"wrote {len(rel)} file(s)" if rel else "up to date"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
